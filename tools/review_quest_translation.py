def main() -> None:
    with CATALOGUE.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))

    missing = sorted(set(OVERRIDES) - {row["english"] for row in rows})
    if missing:
        raise SystemExit(f"Override keys not found: {missing}")

    for row in rows:
        if row["english"] in OVERRIDES:
            row["russian"] = OVERRIDES[row["english"]]
        row["status"] = "reviewed"

    with CATALOGUE.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=("file", "line", "english", "russian", "status"), delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Reviewed {len(rows)} strings ({len(OVERRIDES)} manual overrides)")


